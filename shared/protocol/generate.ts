// Generates the TypeScript and GDScript codecs from shared/protocol/messages.json.
// Run: npm run protocol:gen. CI regenerates and fails if the committed output differs.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const TS_OUT = join(HERE, "generated", "protocol.ts");
const GD_OUT = join(ROOT, "client", "scripts", "net", "generated", "protocol.gd");

type Prim =
  | "u8"
  | "u16"
  | "u32"
  | "i8"
  | "i16"
  | "i32"
  | "f32"
  | "bool"
  | "string"
  | "pos"
  | "vel"
  | "angle"
  | "bytes";
interface ArrayType {
  array: string;
  max: number;
}
interface Field {
  name: string;
  type: Prim | string | ArrayType;
}
interface Message {
  id: number;
  name: string;
  dir: string;
  channel: string;
  fields: Field[];
}
interface Schema {
  version: number;
  structs: Record<string, Field[]>;
  messages: Message[];
}

const PRIMS = new Set<string>([
  "u8",
  "u16",
  "u32",
  "i8",
  "i16",
  "i32",
  "f32",
  "bool",
  "string",
  "pos",
  "vel",
  "angle",
  "bytes",
]);
const schema = JSON.parse(readFileSync(join(HERE, "messages.json"), "utf8")) as Schema;

// ---------- validation ----------
function checkType(t: Field["type"], where: string): void {
  if (typeof t === "string") {
    if (!PRIMS.has(t) && !(t in schema.structs)) throw new Error(`${where}: unknown type ${t}`);
  } else {
    if (t.max < 1 || t.max > 65535) throw new Error(`${where}: bad array max`);
    checkType(t.array, where);
  }
}
const ids = new Set<number>();
for (const m of schema.messages) {
  if (ids.has(m.id) || m.id < 1 || m.id > 255) throw new Error(`bad/duplicate id ${m.id}`);
  ids.add(m.id);
  for (const f of m.fields) checkType(f.type, `${m.name}.${f.name}`);
}
for (const [s, fields] of Object.entries(schema.structs))
  for (const f of fields) checkType(f.type, `${s}.${f.name}`);

const HEADER =
  "AUTO-GENERATED by shared/protocol/generate.ts from shared/protocol/messages.json. DO NOT EDIT.";

// ---------- TypeScript ----------
function tsType(t: Field["type"]): string {
  if (typeof t !== "string") return `${tsType(t.array)}[]`;
  switch (t) {
    case "bool":
      return "boolean";
    case "string":
      return "string";
    case "pos":
    case "vel":
      return "Vec3";
    case "bytes":
      return "Uint8Array";
    default:
      return PRIMS.has(t) ? "number" : t;
  }
}
function tsWrite(t: Field["type"], expr: string, depth = 0): string {
  if (typeof t !== "string") {
    const v = `e${depth}`;
    return `w.arrayLen(${expr}.length, ${t.max}); for (const ${v} of ${expr}) { ${tsWrite(t.array, v, depth + 1)} }`;
  }
  if (PRIMS.has(t)) return `w.${t}(${expr});`;
  return `write${t}(w, ${expr});`;
}
function tsRead(t: Field["type"], depth = 0): string {
  if (typeof t !== "string") {
    const n = `n${depth}`;
    return `(() => { const ${n} = r.arrayLen(${t.max}); const a: ${tsType(t.array)}[] = []; for (let i = 0; i < ${n}; i++) a.push(${tsRead(t.array, depth + 1)}); return a; })()`;
  }
  if (PRIMS.has(t)) return `r.${t}()`;
  return `read${t}(r)`;
}
function tsFieldsInterface(fields: Field[]): string {
  return fields.map((f) => `  ${f.name}: ${tsType(f.type)};`).join("\n");
}

let ts = `// ${HEADER}\n/* eslint-disable */\nimport { Reader, Writer, type Vec3 } from "../codec.ts";\nexport type { Vec3 } from "../codec.ts";\n\n`;
ts += `export const PROTOCOL_VERSION = ${schema.version};\n\n`;
ts += `export const MsgId = {\n${schema.messages.map((m) => `  ${m.name}: ${m.id},`).join("\n")}\n} as const;\n\n`;
ts += `export const MsgChannel: Record<number, "reliable" | "unreliable"> = {\n${schema.messages.map((m) => `  ${m.id}: "${m.channel}",`).join("\n")}\n};\n\n`;
for (const [name, fields] of Object.entries(schema.structs)) {
  ts += `export interface ${name} {\n${tsFieldsInterface(fields)}\n}\n`;
  ts += `function write${name}(w: Writer, v: ${name}): void {\n${fields.map((f) => `  ${tsWrite(f.type, `v.${f.name}`)}`).join("\n")}\n}\n`;
  ts += `function read${name}(r: Reader): ${name} {\n  return {\n${fields.map((f) => `    ${f.name}: ${tsRead(f.type)},`).join("\n")}\n  };\n}\n\n`;
}
for (const m of schema.messages) {
  ts += `export interface ${m.name}Msg {\n  type: "${m.name}";\n${tsFieldsInterface(m.fields)}\n}\n`;
}
ts += `\nexport type Message =\n${schema.messages.map((m) => `  | ${m.name}Msg`).join("\n")};\n\n`;
ts += `export function encode(msg: Message, w: Writer = new Writer()): Uint8Array {\n  switch (msg.type) {\n`;
for (const m of schema.messages) {
  ts += `    case "${m.name}": {\n      w.u8(${m.id});\n${m.fields.map((f) => `      ${tsWrite(f.type, `msg.${f.name}`)}`).join("\n")}\n      break;\n    }\n`;
}
ts += `  }\n  return w.finish();\n}\n\n`;
ts += `export function decode(bytes: Uint8Array): Message {\n  const r = new Reader(bytes);\n  const id = r.u8();\n  let msg: Message;\n  switch (id) {\n`;
for (const m of schema.messages) {
  ts += `    case ${m.id}:\n      msg = {\n        type: "${m.name}",\n${m.fields.map((f) => `        ${f.name}: ${tsRead(f.type)},`).join("\n")}\n      };\n      break;\n`;
}
ts += `    default:\n      throw new Error(\`unknown message id \${id}\`);\n  }\n  r.expectEnd();\n  return msg;\n}\n`;

// ---------- GDScript ----------
function gdWrite(t: Field["type"], expr: string, indent: string, depth = 0): string {
  if (typeof t !== "string") {
    const v = `e${depth}`;
    return `${indent}var arr${depth}: Array = ${expr}\n${indent}w.array_len(arr${depth}.size(), ${t.max})\n${indent}for ${v}: Variant in arr${depth}:\n${gdWrite(t.array, v, indent + "\t", depth + 1)}`;
  }
  if (PRIMS.has(t)) return `${indent}w.put_${t}(${expr})\n`;
  return `${indent}_write_${snake(t)}(w, ${expr})\n`;
}
function gdRead(t: Field["type"], target: string, indent: string, depth = 0): string {
  if (typeof t !== "string") {
    const n = `n${depth}`;
    const a = `arr${depth}`;
    let s = `${indent}var ${n}: int = r.array_len(${t.max})\n${indent}var ${a}: Array = []\n${indent}for _i${depth}: int in ${n}:\n`;
    s += gdRead(t.array, `${a}.append`, indent + "\t", depth + 1);
    s += `${indent}${assign(target, a)}\n`;
    return s;
  }
  const value = PRIMS.has(t) ? `r.get_${t}()` : `_read_${snake(t)}(r)`;
  return `${indent}${assign(target, value)}\n`;
}
function assign(target: string, value: string): string {
  return target.endsWith(".append") ? `${target}(${value})` : `${target} = ${value}`;
}
function snake(s: string): string {
  return s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

let gd = `# ${HEADER}\n# Messages are Dictionaries: {"type": "<Name>", <field>: <value>, ...}. pos/vel fields are Vector3.\nclass_name Protocol\nextends RefCounted\n\nconst PROTOCOL_VERSION: int = ${schema.version}\n\n`;
for (const m of schema.messages) gd += `const MSG_${snake(m.name).toUpperCase()}: int = ${m.id}\n`;
gd += `\nconst MSG_NAMES: Dictionary = {\n${schema.messages.map((m) => `\t${m.id}: "${m.name}",`).join("\n")}\n}\n\n`;
gd += `const UNRELIABLE: Dictionary = {\n${schema.messages
  .filter((m) => m.channel === "unreliable")
  .map((m) => `\t${m.id}: true,`)
  .join("\n")}\n}\n\n`;
for (const [name, fields] of Object.entries(schema.structs)) {
  gd += `static func _write_${snake(name)}(w: ProtocolCodec.Writer, v: Dictionary) -> void:\n`;
  for (const f of fields) gd += gdWrite(f.type, `v["${f.name}"]`, "\t");
  gd += `\n\nstatic func _read_${snake(name)}(r: ProtocolCodec.Reader) -> Dictionary:\n\tvar v: Dictionary = {}\n`;
  for (const f of fields) gd += gdRead(f.type, `v["${f.name}"]`, "\t");
  gd += `\treturn v\n\n\n`;
}
gd += `static func encode(msg: Dictionary) -> PackedByteArray:\n\tvar w := ProtocolCodec.Writer.new()\n\tvar type_name: String = msg["type"]\n\tmatch type_name:\n`;
for (const m of schema.messages) {
  gd += `\t\t"${m.name}":\n\t\t\tw.put_u8(${m.id})\n`;
  for (const f of m.fields) gd += gdWrite(f.type, `msg["${f.name}"]`, "\t\t\t");
  if (m.fields.length === 0) gd += `\t\t\tpass\n`;
}
gd += `\t\t_:\n\t\t\tpush_error("Protocol.encode: unknown message type %s" % type_name)\n\t\t\treturn PackedByteArray()\n\treturn w.finish()\n\n\n`;
gd += `## Returns an empty Dictionary when the bytes are malformed.\nstatic func decode(bytes: PackedByteArray) -> Dictionary:\n\tvar r := ProtocolCodec.Reader.new(bytes)\n\tvar msg: Dictionary = {}\n\tvar id: int = r.get_u8()\n\tmatch id:\n`;
for (const m of schema.messages) {
  gd += `\t\t${m.id}:\n\t\t\tmsg["type"] = "${m.name}"\n`;
  for (const f of m.fields) gd += gdRead(f.type, `msg["${f.name}"]`, "\t\t\t");
}
gd += `\t\t_:\n\t\t\treturn {}\n\tif not r.ok_and_finished():\n\t\treturn {}\n\treturn msg\n`;

mkdirSync(dirname(TS_OUT), { recursive: true });
mkdirSync(dirname(GD_OUT), { recursive: true });
writeFileSync(TS_OUT, ts);
writeFileSync(GD_OUT, gd);
console.log(
  `✓ protocol v${schema.version}: ${schema.messages.length} messages → ${TS_OUT}, ${GD_OUT}`,
);
